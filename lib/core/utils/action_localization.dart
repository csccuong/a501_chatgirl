  static String getLocalizedName(dynamic rawName) {
    if (rawName == null) return '';
    final nameStr = rawName.toString().trim();
    if (nameStr.isEmpty) return '';

    // 1. Try GetX .tr first
    final trValue = nameStr.tr;
    if (trValue.isNotEmpty && trValue != nameStr) {
      return trValue;
    }

    // 2. Match with localized dictionary by selected language
    final langCode = Get.locale?.languageCode.toLowerCase() ?? 'en';
    final dict = _translations[langCode];
    if (dict != null && dict.containsKey(nameStr)) {
      return dict[nameStr]!;
    }

    return nameStr;
  }
